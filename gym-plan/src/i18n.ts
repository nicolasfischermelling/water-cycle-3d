export function translate(lang: Lang, key: string, params?: Params): string {
  let s = lang === 'es' ? (ES[key] ?? key) : key
  if (s === 'Back_') s = 'Back'
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v))
  return s
}

/** Muscle names share a key with "Back" (the nav button), so they get a prefix. */
export const muscleKey = (m: string) => (m === 'Back' ? 'Back_' : m)

export function useT() {
  const { state } = useStore()
  const lang = state.settings.lang
  const t = useCallback<T>((key, params) => translate(lang, key, params), [lang])
  return { t, lang }
}
